#!/usr/bin/env python3
"""
check_generated_tests.py - checks the `test_flow.py` generated by the model.

Why this script exists: the prompt asks for mocked, offline tests, but a prompt
is an instruction, not a guarantee. In a real run the model generated a test
that decorated `@patch('requests.post')` and then called
`requests.Session().post(...)` - the patch does not intercept that path, and the
test tried to resolve `cpi-dev.company.corp` for real. The hostname existed
neither in the artifact nor in the prompt: it was invented.

The risk is not the DNS failing on the runner: it is the name resolving. In that
case, a runner on the internet would make a real request to an internal host.

Checks:

  1. network call whose OWN test has no mock. Scoped per block: a mock in another test
     does not cover it, which is how a real call used to pass;
  2. internal or invented host that is neither a namespace URI nor a test host;
  3. fixed port in a local mock server (collides between suites in parallel);
  4. a SOAP Fault lookup that qualifies a child with the envelope namespace. Those
     children are unqualified, so the lookup always returns None - a wrong assertion
     that fails on a correct mock.

Exit codes: 0 = nothing suspicious, 1 = findings, 2 = invalid usage.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Hosts
# ---------------------------------------------------------------------------

# XML namespace hosts and schema URIs: they appear legitimately in fixtures and
# in SOAP envelopes. They are not an attempt to connect.
NAMESPACE_PATTERNS = (
    "schemas.xmlsoap.org",
    "schemas.microsoft.com",
    "soap.sforce.com",
    "www.w3.org",
    "www.omg.org",
    "sap.com",
    "oasis-open.org",
    "example.com",
    "example.org",
    "example.net",
)

# `.invalid` is reserved for documentation (RFC 2606) and exists precisely to
# replace real hosts.
RESERVED_SUFFIXES = (".invalid", ".test", ".example")

INTERNAL_SUFFIXES = (".corp", ".internal", ".local", ".lan", ".intranet")

# The exact list depends on the client; it must not be hardcoded.
EXTRA_SUFFIXES = tuple(
    s.strip().lower()
    for s in os.environ.get("FORBIDDEN_HOST_SUFFIXES", "").split(",")
    if s.strip()
)

URL_PATTERN = re.compile(r"https?://([A-Za-z0-9._-]+)")

LOCAL_HOSTS = {"localhost", "127.0.0.1", "0.0.0.0", "::1", "host.docker.internal"}

# ---------------------------------------------------------------------------
# Network calls and mock coverage
# ---------------------------------------------------------------------------

# Each target carries the name of the mock that intercepts it. `requests.Session()`
# counts as a call: it was exactly the path that escaped `@patch('requests.post')`.
NETWORK_TARGETS = (
    ("requests.post", re.compile(r"\brequests\.post\s*\(")),
    ("requests.get", re.compile(r"\brequests\.get\s*\(")),
    ("requests.put", re.compile(r"\brequests\.put\s*\(")),
    ("requests.patch", re.compile(r"\brequests\.patch\s*\(")),
    ("requests.delete", re.compile(r"\brequests\.delete\s*\(")),
    ("requests.request", re.compile(r"\brequests\.request\s*\(")),
    ("requests.Session", re.compile(r"\brequests\.Session\s*\(")),
    ("urlopen", re.compile(r"\burlopen\s*\(")),
)

# Mock forms that make the call safe.
MOCKS = (
    ("responses", re.compile(r"\bresponses\b")),
    ("patch", re.compile(r"\bpatch(?:\.object)?\s*\(")),
    ("MagicMock", re.compile(r"\bMagicMock\s*\(")),
    ("Mock", re.compile(r"\bMock\s*\(")),
    ("monkeypatch", re.compile(r"\bmonkeypatch\b")),
    ("requests_mock", re.compile(r"\brequests_mock\b")),
    ("httpretty", re.compile(r"\bhttpretty\b")),
)

# In SOAP 1.1 only `Fault` is in the envelope namespace. Its children are UNQUALIFIED, so a
# lookup that attaches the envelope namespace to one of them returns None.
#
# SOAP 1.2 is deliberately NOT included: there the envelope is
# `http://www.w3.org/2003/05/soap-envelope` and `Code`, `Reason` and `Detail` ARE in that
# namespace, so qualifying them is correct. A probe asserted otherwise and the probe was
# wrong.
SOAP_11_ENVELOPE_URIS = ("http://schemas.xmlsoap.org/soap/envelope/",)

UNQUALIFIED_FAULT_CHILDREN = ("faultcode", "faultstring", "faultactor")

# `{<literal>}faultstring`: the URI written inline in the lookup.
_NAMESPACE_LITERAL = re.compile(
    r"""\{\s*["']?(?P<uri>https?://[^}"']+)["']?\s*\}\s*(?P<child>\w+)"""
)

# `f".//{ENV}faultstring"`: the URI held in a name. Resolved against the assignments below.
_NAMESPACE_VARIABLE = re.compile(r"""\{\s*(?P<var>[A-Za-z_]\w*)\s*\}\s*(?P<child>\w+)""")

# `ENV = "{http://...}"` or `ENV = "http://..."`, with or without an f-prefix nearby.
_URI_ASSIGNMENT = re.compile(
    r"""^(?P<indent>\s*)(?P<name>[A-Za-z_]\w*)\s*=\s*["']"""
    r"""(?:\{(?P<braced>https?://[^}"']+)\}|(?P<plain>https?://[^"']+))["']"""
)

FIXED_PORT_PATTERNS = (
    # explicit binding: HTTPServer(("localhost", 18080), ...)
    re.compile(r"\(\s*[\"'][^\"']*[\"']\s*,\s*(\d+)\s*\)"),
    # keyword argument: port=18080
    re.compile(r"\bport\s*=\s*(\d+)"),
)


class Finding:
    def __init__(self, line: int, category: str, detail: str):
        self.line = line
        self.category = category
        self.detail = detail

    def __str__(self) -> str:
        return f"line {self.line}: [{self.category}] {self.detail}"


def is_namespace(host: str) -> bool:
    host = host.lower()
    return any(host == n or host.endswith("." + n) for n in NAMESPACE_PATTERNS)


def suspicious_host(host: str) -> str | None:
    """
    Returns the reason when the host should not appear in a test, or None.

    An unknown public host is suspicious too: the test promises to use only
    mocks, so any resolvable domain is a risk of real I/O.
    """
    host = host.lower().strip(".")

    if host in LOCAL_HOSTS:
        return None
    if is_namespace(host):
        return None
    if any(host.endswith(s) for s in RESERVED_SUFFIXES):
        return None

    if host.replace(".", "").isdigit():
        return None if host.startswith("127.") else f"external IP '{host}'"

    for suffix in (*INTERNAL_SUFFIXES, *EXTRA_SUFFIXES):
        if host.endswith(suffix):
            return f"internal host '{host}'"

    if "." in host:
        return f"external host '{host}' (the test must use mocks only)"

    return None


# ---------------------------------------------------------------------------
# Scoping the mocks
# ---------------------------------------------------------------------------

# A top-level definition: `def name(` or `class Name` with no indentation.
_TOP_LEVEL_DEF = re.compile(r"^(?:async\s+)?(?:def|class)\s+\w+")


def _has_mock(body: str) -> bool:
    """True when this text declares mock coverage of some kind."""
    return any(pattern.search(body) for _name, pattern in MOCKS)


def _split_blocks(lines: list[str]) -> dict[str, list]:
    """
    Group the file into the header, each top-level definition, and their line ranges.

    Returns `{"header": [(text, start_line)], "functions": [(body, start_line), ...],
    "helpers": [(body, start_line), ...]}`. A "helper" is a function that makes no network
    call of its own: it is the case where a test delegates to a module-level function, and
    flagging that would be a false positive.
    """
    boundaries: list[tuple[int, str]] = []
    for index, line in enumerate(lines):
        if _TOP_LEVEL_DEF.match(line):
            boundaries.append((index, line.strip()))

    header_lines = lines[: boundaries[0][0]] if boundaries else lines
    blocks: dict[str, list] = {
        "header": [("\n".join(header_lines), 1)],
        "functions": [],
        "helpers": [],
    }

    for position, (start, signature) in enumerate(boundaries):
        end = boundaries[position + 1][0] if position + 1 < len(boundaries) else len(lines)
        body = "\n".join(lines[start:end])
        entry = (body, start + 1)
        # A nested function definition is part of its parent, not a block of its own.
        if len(signature) != len(signature.lstrip()):
            continue
        if any(pattern.search(body) for _name, pattern in NETWORK_TARGETS):
            blocks["functions"].append(entry)
        else:
            blocks["helpers"].append(entry)

    return blocks


def _covered(line_number: int, blocks: dict, helper_has_mock: bool) -> bool:
    """
    True when the network call on this line sits in a block that has its own mock.

    A block that makes no call of its own but delegates to a helper is exempt when the
    helper has a mock: the call is then made on the helper's behalf, inside its mocked body.
    """
    for body, start in blocks["functions"]:
        if start <= line_number < start + len(body.splitlines()):
            if _has_mock(body):
                return True
            # The call may be delegated: the block imports or calls a helper by name.
            for helper_body, _helper_start in blocks["helpers"]:
                name = _defined_name(helper_body)
                if name and re.search(rf"\b{re.escape(name)}\s*\(", body):
                    return helper_has_mock
            return False

    # Module level: the header has to carry the mock itself.
    header_body = blocks["header"][0][0] if blocks["header"] else ""
    return _has_mock(header_body)


def _defined_name(body: str) -> str | None:
    match = re.match(r"^(?:async\s+)?(?:def|class)\s+(\w+)", body.lstrip())
    return match.group(1) if match else None


def check(path: Path, allowed: set[str] | None = None) -> list[Finding]:
    text = path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    allowed = allowed or set()
    findings: list[Finding] = []

    def ignored(line: str) -> bool:
        return line.lstrip().startswith("#")

    # --- network call ------------------------------------------------------
    # Mock coverage is scoped to the block that makes the call. Checking it over the whole
    # file approved anything as soon as ONE mock existed somewhere: a test that posted for
    # real was cleared by an unrelated test's `@responses.activate`. Measured, not assumed
    # - see the probes in the test suite.
    blocks = _split_blocks(lines)
    helper_has_mock = any(_has_mock(body) for body, _start in blocks["helpers"])

    for line_number, line in enumerate(lines, start=1):
        if ignored(line):
            continue
        for name, pattern in NETWORK_TARGETS:
            if not pattern.search(line):
                continue
            if not _covered(line_number, blocks, helper_has_mock):
                findings.append(
                    Finding(
                        line_number,
                        "network",
                        f"'{name}' has no mock in the test that calls it",
                    )
                )
            break

    # --- hosts -------------------------------------------------------------
    for line_number, line in enumerate(lines, start=1):
        if ignored(line):
            continue
        for match in URL_PATTERN.finditer(line):
            host = match.group(1)
            if host.lower() in allowed:
                continue
            reason = suspicious_host(host)
            if reason:
                findings.append(Finding(line_number, "host", reason))

    # --- fixed port --------------------------------------------------------
    for line_number, line in enumerate(lines, start=1):
        if ignored(line):
            continue
        for pattern in FIXED_PORT_PATTERNS:
            match = pattern.search(line)
            if not match or match.group(1) == "0":
                continue
            findings.append(
                Finding(
                    line_number,
                    "port",
                    f"fixed port {match.group(1)}; use port=0 or an environment variable",
                )
            )
            break

    # --- SOAP Fault namespace ---------------------------------------------
    # A lookup that qualifies a Fault child with the envelope namespace always returns
    # None. It is a wrong assertion, not a network risk, and it made every generated suite
    # fail on a correct mock.
    # Names assigned a SOAP 1.1 envelope URI anywhere in the file, so `{ENV}faultstring`
    # can be resolved without executing anything.
    envelope_names: set[str] = set()
    for line in lines:
        assignment = _URI_ASSIGNMENT.match(line)
        if not assignment:
            continue
        uri = (assignment.group("braced") or assignment.group("plain") or "").rstrip("/")
        if uri.lower() in {known.rstrip("/").lower() for known in SOAP_11_ENVELOPE_URIS}:
            envelope_names.add(assignment.group("name"))

    def offending_uri(match: re.Match) -> str | None:
        """The envelope URI the lookup uses, or None when it is not the 1.1 envelope."""
        try:
            uri = match.group("uri")
        except IndexError:
            variable = match.group("var")
            if variable not in envelope_names:
                return None
            return SOAP_11_ENVELOPE_URIS[0]
        return uri if uri.rstrip("/").lower() in {
            known.rstrip("/").lower() for known in SOAP_11_ENVELOPE_URIS
        } else None

    for line_number, line in enumerate(lines, start=1):
        if ignored(line):
            continue
        for pattern in (_NAMESPACE_LITERAL, _NAMESPACE_VARIABLE):
            for match in pattern.finditer(line):
                child = match.group("child").lower()
                if child not in UNQUALIFIED_FAULT_CHILDREN:
                    continue
                if offending_uri(match) is None:
                    continue
                findings.append(
                    Finding(
                        line_number,
                        "soap-namespace",
                        f"'{child}' is UNQUALIFIED in SOAP 1.1 and has no namespace; "
                        f"'{match.group(0)}' always resolves to None. Use "
                        f"fault.find('{child}') instead",
                    )
                )

    return findings


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Checks the generated test_flow.py: network without mock, hosts and fixed port."
    )
    parser.add_argument("path", help="test_flow.py file to check.")
    parser.add_argument(
        "--allow",
        action="append",
        default=[],
        help="Extra host to allow (may be repeated).",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="Do not print the final explanatory text.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)

    path = Path(args.path)
    if not path.is_file():
        print(f"[ERROR] file not found: {path}", file=sys.stderr)
        return 2

    findings = check(path, {h.lower() for h in args.allow})

    if not findings:
        print(f"OK: no suspicious occurrence in {path.name}")
        return 0

    print(f"::error::{len(findings)} suspicious occurrence(s) in {path.name}")
    for finding in findings:
        print(f"  {finding}")

    if not args.quiet:
        print("")
        print("A generated test that touches the real network is a defect: the runner")
        print("has no access to internal hosts and, if the name resolved, the request")
        print("would go out for real. Fix the test or the prompt; legitimate host -> --allow.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
