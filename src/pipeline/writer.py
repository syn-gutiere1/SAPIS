"""
writer.py - writing of the artifacts generated by the model.

Two critical responsibilities:

1. **Sanitization of filenames.** The name comes from the LLM response, which in turn
   was influenced by the `.iflw` - an untrusted input. The original pipeline did
   `(out_dir / item["file"]).write_text(...)` directly, which allows
   `"../../anything.py"` to write outside the destination folder. Here every name goes
   through `safe_relative_path()`, which reduces it to a simple name and rejects the rest.

2. **Cleanup of the destination folder.** The original pipeline never cleaned the output.
   Observed result: `generated/SI_Glovia_SalesOrderCreate/testdata/` had 41
   files while the current run declared only 13 - leftover from previous runs.
   In CI this produces an unreliable result (tests read old fixtures
   and the number of tests changes without the code having changed).
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from pipeline import extract as _extract

# Extensions accepted for the test fixtures. Whitelist: anything else is
# rejected, instead of being written.
ALLOWED_TESTDATA_SUFFIXES = {
    ".xml",
    ".json",
    ".txt",
    ".csv",
    ".xsd",
    ".xslt",
    ".properties",
    ".yaml",
    ".yml",
}

# Reserved names: they are artifacts of the pipeline itself and cannot be
# overwritten by a fixture coming from the model.
RESERVED_NAMES = {
    "test_flow.py",
    "cases.json",
    "risks.json",
    "coverage.json",
    "raw_llm_output.json",
    "manifest.json",
}

# Filenames that operating systems use for devices.
RESERVED_DEVICE_NAMES = {
    "con", "prn", "aux", "nul",
    "com1", "com2", "com3", "com4", "com5", "com6", "com7", "com8", "com9",
    "lpt1", "lpt2", "lpt3", "lpt4", "lpt5", "lpt6", "lpt7", "lpt8", "lpt9",
}


class WriteError(Exception):
    """Failure while writing the generated artifacts."""


# ---------------------------------------------------------------------------
# Sanitization
# ---------------------------------------------------------------------------


def safe_relative_path(candidate: Any, *, allowed_suffixes: set[str] | None = None) -> str:
    """
    Converts a name coming from the model into a simple and safe filename.

    Rules (from section 4.3 of the analysis, high severity finding):
      - only the base name is considered; directories are discarded, which
        eliminates `../` and absolute paths;
      - alternative Windows separators are normalized beforehand;
      - empty names, `.` and `..` are rejected;
      - names reserved by the pipeline and by devices are rejected;
      - the extension must be in the whitelist, when one is provided.

    Raises `WriteError` instead of writing something suspicious.
    """
    if not isinstance(candidate, str):
        raise WriteError(f"Invalid filename (text expected): {candidate!r}")

    raw = candidate.strip().replace("\\", "/")
    raw = raw.strip('"').strip("'")

    if not raw:
        raise WriteError("Empty filename.")

    # `Path(...).name` discards any directory component, including `..`
    # and the root of an absolute path.
    name = Path(raw).name.strip()

    if name in ("", ".", ".."):
        raise WriteError(f"Invalid filename: {candidate!r}")

    stem = Path(name).stem.lower()
    if stem in RESERVED_DEVICE_NAMES:
        raise WriteError(f"Filename reserved by the system: {name!r}")

    if name.lower() in RESERVED_NAMES:
        raise WriteError(
            f"Name reserved for the pipeline: {name!r}. A fixture cannot "
            "overwrite a generated artifact."
        )

    if allowed_suffixes is not None:
        suffix = Path(name).suffix.lower()
        if suffix not in allowed_suffixes:
            raise WriteError(
                f"Extension not allowed for fixture: {name!r} "
                f"(allowed: {', '.join(sorted(allowed_suffixes))})"
            )

    return name


def _ensure_within(base: Path, target: Path) -> None:
    """
    Confirms that the resolved path stays inside `base`.

    Defense in depth: `safe_relative_path()` already eliminates path traversal, but
    this check guarantees that a future change does not reintroduce the problem.
    """
    base_resolved = base.resolve()
    target_resolved = target.resolve()
    if not target_resolved.is_relative_to(base_resolved):
        raise WriteError(
            f"Path outside the destination directory: {target_resolved} "
            f"(allowed only inside {base_resolved})"
        )


# ---------------------------------------------------------------------------
# Flexible reading of the model response
# ---------------------------------------------------------------------------


def find_key(data: Any, keywords: list[str]) -> Any:
    """
    Looks for a key by substring, case-insensitively.

    Kept for compatibility with the original behavior. F5 replaces this
    heuristic with structured output (JSON Schema) in the Portkey call.
    """
    if not isinstance(data, dict):
        return None
    for key, value in data.items():
        lowered = key.lower()
        if any(keyword in lowered for keyword in keywords):
            return value
    return None


def _normalize_scenarios(package: Any) -> list:
    value = find_key(package, ["scenario", "scenarios"]) or []
    if isinstance(value, dict):
        return list(value.values())
    return value if isinstance(value, list) else []


def _normalize_risks(package: Any) -> list:
    value = find_key(package, ["risk", "risks"]) or []
    if isinstance(value, dict):
        return list(value.values())
    return value if isinstance(value, list) else []


def _normalize_testdata(package: Any) -> list[dict]:
    value = find_key(package, ["test_data", "test data", "testdata"])
    if isinstance(value, dict):
        value = [value]
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, dict)]


def _normalize_pytest_code(package: Any) -> str:
    value = find_key(package, ["pytest", "script"]) or ""

    if isinstance(value, list):
        return "\n".join(str(part) for part in value)
    if isinstance(value, dict):
        if "content" in value:
            return str(value["content"])
        if "test_flow.py" in value:
            return str(value["test_flow.py"])
        return "\n".join(str(part) for part in value.values())
    return str(value)


