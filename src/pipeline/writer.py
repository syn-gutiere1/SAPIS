# Writing
# ---------------------------------------------------------------------------


def clean_output_dir(directory: Path) -> None:
    """
    Removes the contents of an output directory before rewriting it.

    Prevents fixtures from previous runs from surviving and altering the test
    result. If removal is not possible, raises `WriteError` instead of
    continuing with a potentially dirty folder.
    """
    directory = Path(directory)
    if not directory.exists():
        return

    for child in directory.iterdir():
        try:
            if child.is_dir() and not child.is_symlink():
                shutil.rmtree(child)
            else:
                child.unlink()
        except OSError as exc:
            raise WriteError(
                f"Could not clean {child}: {exc}. The output folder must "
                "be clean for the run result to be reliable."
            ) from exc


def write_test_package(
    package: Any,
    out_dir: str | Path,
    *,
    clean: bool = True,
    flow_xml: str | None = None,
) -> dict[str, Any]:
    """
    Writes the artifacts from the model and returns a summary of what was written.

    Files generated in `out_dir`:
        cases.json          scenarios of the unified plan
        testdata/*          fixtures used by the tests
        test_flow.py        pytest suite
        risks.json          identified risks
        coverage.json       coverage analysis of the model, plus the reachability of the
                            artifact's BPMN elements, which is computed here
        raw_llm_output.json full model response (audit)
    """
    out_dir = Path(out_dir)

    if clean:
        clean_output_dir(out_dir)

    testdata_dir = out_dir / "testdata"
    testdata_dir.mkdir(parents=True, exist_ok=True)

    written: list[str] = []
    rejected: list[str] = []

    # --- scenarios --------------------------------------------------------
    scenarios = _normalize_scenarios(package)
    cases_path = out_dir / "cases.json"
    cases_path.write_text(
        json.dumps(scenarios, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    written.append("cases.json")

    # --- fixtures ---------------------------------------------------------
    seen: set[str] = set()
    for item in _normalize_testdata(package):
        raw_name = item.get("filename") or item.get("file")
        content = item.get("content")

        if raw_name is None or content is None:
            rejected.append(f"{item!r} (missing 'filename' or 'content')")
            continue
        if not isinstance(content, str):
            content = json.dumps(content, ensure_ascii=False, indent=2)

        try:
            name = safe_relative_path(raw_name, allowed_suffixes=ALLOWED_TESTDATA_SUFFIXES)
        except WriteError as exc:
            rejected.append(f"{raw_name!r}: {exc}")
            continue

        if name in seen:
            rejected.append(f"{name!r}: declared more than once in the same response")
            continue
        seen.add(name)

        target = testdata_dir / name
        _ensure_within(testdata_dir, target)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written.append(f"testdata/{name}")

    # --- pytest suite -----------------------------------------------------
    pytest_code = _normalize_pytest_code(package)
    if pytest_code.strip():
        (out_dir / "test_flow.py").write_text(pytest_code, encoding="utf-8")
        written.append("test_flow.py")

    # --- risks ------------------------------------------------------------
    risks = _normalize_risks(package)
    (out_dir / "risks.json").write_text(
        json.dumps(risks, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    written.append("risks.json")

    # --- coverage ---------------------------------------------------------
    # The model estimates the percentages; the reachability of the BPMN elements is
    # computed from the artifact and merged in. An element wired to nothing is at 0 %
    # whatever the model says, and leaving that to the model meant a real 0 % entry
    # appeared in one generation and vanished in the next.
    coverage = find_key(package, ["coverage"])
    if coverage is None and flow_xml:
        coverage = {}
    if coverage is not None:
        if flow_xml:
            try:
                coverage = _extract.merge_unreachable(coverage, flow_xml)
            except Exception:  # noqa: BLE001 - never lose the model's own report
                pass
        (out_dir / "coverage.json").write_text(
            json.dumps(coverage, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        written.append("coverage.json")

    # --- raw response (audit) ---------------------------------------------
    (out_dir / "raw_llm_output.json").write_text(
        json.dumps(package, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    written.append("raw_llm_output.json")

    return {
        "out_dir": str(out_dir),
        "files": written,
        "rejected": rejected,
        "scenarios": len(scenarios) if isinstance(scenarios, list) else 0,
        "risks": len(risks) if isinstance(risks, list) else 0,
        "testdata_files": len(seen),
    }
